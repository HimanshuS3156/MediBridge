// Converts an ISO2 code ('IN', 'US', ...) to its flag emoji ('🇮🇳', '🇺🇸', ...)
// by mapping each letter to its Regional Indicator Symbol code point.
function countryFlagEmoji(iso2) {
  if (!iso2 || iso2.length !== 2) return '';
  const codePoints = iso2.toUpperCase().split('').map(c => 0x1F1E6 + (c.charCodeAt(0) - 65));
  return String.fromCodePoint(...codePoints);
}
